#include <iostream>

using namespace std;

int main()
{
    int X, Y;

    cin >> X;
    cin >> Y;

    cout << X << " + " << Y << " = " << (X + Y) << "\n";
    cout << X << " * " << Y << " = " << (X * Y) << "\n";
    cout << X << " - " << Y << " = " << (X - Y) << "\n";

    return 0;
}
